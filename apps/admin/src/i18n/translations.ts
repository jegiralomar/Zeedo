export const formatCurrency = (amount: number, lang: LanguageCode = 'en'): string => {
  const formattedNumber = (amount || 0).toLocaleString('en-US');
  const symbol = lang === 'en' ? 'IQD' : 'د.ع';
  return `${formattedNumber} ${symbol}`;
};

